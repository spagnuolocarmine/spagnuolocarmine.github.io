import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newState} from '../dist/physics.js';
import {GENERIC_BOAT} from '../dist/boats.js';
import {hasCertifiedPolar} from '../dist/polar-availability.js';
const lab=newState();
assert.equal(lab.boat.id,GENERIC_BOAT.id);
assert.equal(hasCertifiedPolar(lab),false,'generic lab has no polar even if its model estimates a speed');
const validPolar={WindSpeeds:[6,8],WindAngles:[52,75]};
assert.equal(hasCertifiedPolar({...lab,boat:{...GENERIC_BOAT,polar:validPolar}}),false,'generic sloop must never inherit a fabricated polar');
assert.equal(hasCertifiedPolar({...lab,boat:{...GENERIC_BOAT,id:'orc-boat',polar:validPolar}}),true,'ORC polar is visible');
assert.equal(hasCertifiedPolar({...lab,boat:{...GENERIC_BOAT,id:'no-data',polar:null}}),false,'unknown polar must not be displayed');
const app=readFileSync(new URL('../dist/app.js',import.meta.url),'utf8');
const html=readFileSync(new URL('../dist/index.html',import.meta.url),'utf8');
for(const cls of ['.target-instrument','.header-efficiency','.polar-target-metric','.polar-efficiency-metric','#dataPolarChart','#telemetryCertificateNote'])assert.ok(app.includes(`'${cls}'`),`visibility handled: ${cls}`);
assert.match(html,/class="header-instrument target-instrument hidden"/);
assert.match(html,/class="header-instrument header-efficiency hidden"/);
assert.match(html,/class="metric polar-target-metric hidden"/);
assert.match(html,/class="metric polar-efficiency-metric hidden"/);
assert.match(html,/id="responseSpeed" type="range" min="-20" max="20" step="1" value="0"/);
assert.match(html,/<output id="responseSpeedOutput"[^>]+>1×<\/output>/);
assert.doesNotMatch(html,/\+20 · 20×|−20 · 0,05×|0 · 1×/);
console.log('PASS: laboratory cannot show unknown polar targets or efficiency; ORC polar is retained; initial slider range and single multiplier labels.');
